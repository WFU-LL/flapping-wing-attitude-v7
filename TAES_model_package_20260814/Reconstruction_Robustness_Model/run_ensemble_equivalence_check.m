function run_ensemble_equivalence_check()
% Validate the batched direct-Simulink implementation against single runs.

cfg=init_recon_robustness_config();
build_recon_robustness_ensemble_model();
samples=readtable(cfg.sample_file);samples=samples(1:2,:);
job=table(1,"batch_equivalence","moderate","C1_selective", ...
    "inertia-flex-wake",0.3,0.2,10,0.03,20, ...
    'VariableNames',{'job_id','stage','scenario_id','controller', ...
    'mechanism_case','k','delta','delay_ms','noise_rms_fraction', ...
    'filter_cutoff_hz'});
[runs,~,batch_runtimes]=run_recon_ensemble_group(cfg,samples,job);
scenario=struct('k',0.3,'delta',0.2,'delay_ms',10, ...
    'noise_rms_fraction',0.03,'filter_cutoff_hz',20);
conditions={'none','yaw_impulse','multi_axis_sine'};
rows=table();
for si=1:2
    for ci=1:3
        single=run_recon_robustness_case(cfg,samples(si,:), ...
            'inertia-flex-wake',conditions{ci},'C1_selective',scenario);
        batch=runs{ci}(si);
        t=batch.t;
        single_x=interp1(single.t,single.x,t,'linear');
        single_mc=interp1(single.t,single.M_c,t,'linear');
        ms=compute_recon_robustness_metrics(single,[]);
        mb=compute_recon_robustness_metrics(batch,[]);
        max_attitude_difference_deg=max(abs(rad2deg( ...
            batch.x(:,1:3)-single_x(:,1:3))),[],'all');
        max_rate_difference=max(abs(batch.x(:,4:6)-single_x(:,4:6)),[],'all');
        max_control_difference=max(abs(batch.M_c-single_mc),[],'all');
        relative_rmse_error=abs(mb.rmse_norm_deg-ms.rmse_norm_deg)/ ...
            max(abs(ms.rmse_norm_deg),eps);
        relative_energy_error=abs(mb.control_energy_total-ms.control_energy_total)/ ...
            max(abs(ms.control_energy_total),eps);
        relative_rate_energy_error=abs(mb.rate_energy-ms.rate_energy)/ ...
            max(abs(ms.rate_energy),eps);
        relative_final_yaw_error=abs(mb.final_yaw_deg-ms.final_yaw_deg)/ ...
            max(abs(ms.final_yaw_deg),eps);
        pass=max_attitude_difference_deg<=1e-3 && ...
            max_rate_difference<=2e-4 && max_control_difference<=5e-5 && ...
            max([relative_rmse_error,relative_energy_error, ...
            relative_rate_energy_error,relative_final_yaw_error])<=1e-4;
        row=table(samples.sample_id(si),string(conditions{ci}), ...
            max_attitude_difference_deg,max_rate_difference, ...
            max_control_difference,relative_rmse_error,relative_energy_error, ...
            relative_rate_energy_error,relative_final_yaw_error,pass, ...
            'VariableNames',{'sample_id','external_condition', ...
            'max_attitude_difference_deg','max_rate_difference_rad_s', ...
            'max_control_difference_Nm','relative_rmse_error', ...
            'relative_energy_error','relative_rate_energy_error', ...
            'relative_final_yaw_error','pass'});
        rows=[rows;row]; %#ok<AGROW>
        fprintf('ENSEMBLE_EQ_PROGRESS sample=%d condition=%s pass=%d att=%.3e\n', ...
            samples.sample_id(si),conditions{ci},pass,max_attitude_difference_deg);
    end
end
overall_pass=all(rows.pass);
writetable(rows,fullfile(cfg.dirs.verification, ...
    'ensemble_single_equivalence_results.csv'));
fid=fopen(fullfile(cfg.dirs.verification, ...
    'ensemble_single_equivalence_report.md'),'w');
fprintf(fid,'# Batched-versus-Single Direct-Simulink Equivalence\n\n');
fprintf(fid,'- Samples: 2 matched protected V8 samples.\n');
fprintf(fid,'- Conditions: none, yaw impulse, multi-axis sine.\n');
fprintf(fid,'- Ensemble batch runtimes (s): %.3f, %.3f, %.3f.\n',batch_runtimes);
fprintf(fid,'- Maximum attitude difference: %.12g deg.\n', ...
    max(rows.max_attitude_difference_deg));
fprintf(fid,'- Maximum rate difference: %.12g rad/s.\n', ...
    max(rows.max_rate_difference_rad_s));
fprintf(fid,'- Maximum relative metric error: %.12g.\n', ...
    max([rows.relative_rmse_error;rows.relative_energy_error; ...
    rows.relative_rate_energy_error;rows.relative_final_yaw_error]));
fprintf(fid,['- Acceptance limits: attitude `1e-3 deg`, rate `2e-4 rad/s`, ' ...
    'control moment `5e-5 N m`, and relative metrics `1e-4`.\n']);
fprintf(fid,['- The nonzero trajectory residual is caused by ode45 selecting one ' ...
    'adaptive step sequence for the joint independent-state batch. No equation, ' ...
    'parameter, saturation, or plant-side IFA path was changed.\n']);
fprintf(fid,'- ENSEMBLE EQUIVALENCE RESULT: **%s**\n',local_word(overall_pass));
fclose(fid);
if bdIsLoaded('model_recon_robustness_ensemble')
    set_param('model_recon_robustness_ensemble','FastRestart','off');
    close_system('model_recon_robustness_ensemble',0);
end
if bdIsLoaded(cfg.model),close_system(cfg.model,0);end
if ~overall_pass,error('ReconStudy:EnsembleMismatch', ...
        'Batched direct-Simulink implementation failed equivalence.');end
fprintf('ENSEMBLE_EQ_RESULT=PASS max_attitude_diff=%.3e\n', ...
    max(rows.max_attitude_difference_deg));
end

function word=local_word(value)
if value,word='PASS';else,word='FAIL';end
end
