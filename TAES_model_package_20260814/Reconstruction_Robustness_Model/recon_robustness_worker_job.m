function payload = recon_robustness_worker_job(job, sample)
% Run one matched reconstruction job: nominal plus two disturbances.

persistent cfg worker_ready
if isempty(cfg)
    cfg = init_recon_robustness_config();
end
if isempty(worker_ready)
    task = getCurrentTask();
    if isempty(task), tag='client'; else, tag=sprintf('worker_%d',task.ID); end
    sfe_prepare_worker_cache(cfg,['recon_' tag]);
    load_system(cfg.model_file);
    set_param(cfg.model,'SolverType','Variable-step', ...
        'StopTime',num2str(cfg.stop_time,17),'Solver','ode45', ...
        'MaxStep',num2str(cfg.max_step,17),'ReturnWorkspaceOutputs','on', ...
        'OutputOption','SpecifiedOutputTimes', ...
        'OutputTimes',sprintf('0:%.17g:%.17g',cfg.max_step,cfg.stop_time), ...
        'SimulationMode','normal','FastRestart','on');
    worker_ready = true;
end

if istable(job), job=table2struct(job); end
if istable(sample), sample=table2struct(sample); end
scenario = struct('k',job.k,'delta',job.delta,'delay_ms',job.delay_ms, ...
    'noise_rms_fraction',job.noise_rms_fraction, ...
    'filter_cutoff_hz',job.filter_cutoff_hz);
conditions = {'none','yaw_impulse','multi_axis_sine'};
payload = struct('ok',false,'error_message','','rows',table());
task_timer = tic;

try
    nominal = run_recon_robustness_case(cfg,sample,job.mechanism_case, ...
        'none',job.controller,scenario);
    rows = local_row(job,nominal,[],true,'');
    for i = 2:numel(conditions)
        result = run_recon_robustness_case(cfg,sample,job.mechanism_case, ...
            conditions{i},job.controller,scenario);
        rows = [rows;local_row(job,result,nominal,true,'')]; %#ok<AGROW>
    end
    payload.rows = rows;
    payload.ok = true;
catch ME
    payload.error_message = sprintf('%s: %s',ME.identifier,ME.message);
    rows = table();
    for i = 1:numel(conditions)
        rows = [rows;local_failure_row(job,conditions{i}, ...
            payload.error_message,toc(task_timer))]; %#ok<AGROW>
    end
    payload.rows = rows;
end
end

function row = local_row(job,result,nominal,success,message)
m = compute_recon_robustness_metrics(result,nominal);
gain = local_gain(job.controller,job.k);
delta = repmat(job.delta,1,3);
actual = result.noise_meta.actual_rms;
row = table(string(job.stage),string(job.scenario_id), ...
    string(job.controller),string(job.mechanism_case), ...
    string(result.external_condition),job.sample_id, ...
    gain(1),gain(2),gain(3),delta(1),delta(2),delta(3), ...
    job.delay_ms,job.noise_rms_fraction,result.noise_meta.seed, ...
    actual(1),actual(2),actual(3),job.filter_cutoff_hz, ...
    m.rmse_roll_deg,m.rmse_pitch_deg,m.rmse_yaw_deg,m.rmse_norm_deg, ...
    m.final_roll_deg,m.final_pitch_deg,m.final_yaw_deg,m.max_attitude_deg, ...
    m.pitch_ripple_deg,m.rate_energy,m.control_energy_total, ...
    m.control_energy_roll,m.control_energy_pitch,m.control_energy_yaw, ...
    m.compensation_energy,m.disturbance_increment_iae, ...
    m.ifa_saturation_fraction,m.baseline_command_saturation_fraction, ...
    m.compensation_saturation_fraction,m.outer_command_saturation_fraction, ...
    logical(success),string(message),result.runtime_seconds, ...
    'VariableNames',local_schema());
end

function row = local_failure_row(job,external_condition,message,runtime)
gain = local_gain(job.controller,job.k);
delta = repmat(job.delta,1,3);
prefix = {string(job.stage),string(job.scenario_id),string(job.controller), ...
    string(job.mechanism_case),string(external_condition),job.sample_id, ...
    gain(1),gain(2),gain(3),delta(1),delta(2),delta(3),job.delay_ms, ...
    job.noise_rms_fraction,20260712+job.sample_id};
values = [prefix,num2cell(nan(1,24)),{false,string(message),runtime}];
row = cell2table(values,'VariableNames',local_schema());
end

function gain = local_gain(controller,k)
switch char(controller)
    case 'C0_baseline_PD', gain=[0 0 0];
    case {'C1_selective','C3_selective_LPF'}, gain=[k 0 k];
    case 'C2_all_axis', gain=[k k k];
end
end

function names = local_schema()
names = {'stage','scenario_id','controller','mechanism_case', ...
    'external_condition','sample_id','k_roll','k_pitch','k_yaw', ...
    'delta_roll','delta_pitch','delta_yaw','delay_ms','noise_rms_fraction', ...
    'noise_seed','noise_actual_rms_roll','noise_actual_rms_pitch', ...
    'noise_actual_rms_yaw','filter_cutoff_hz','rmse_roll_deg', ...
    'rmse_pitch_deg','rmse_yaw_deg','rmse_norm_deg','final_roll_deg', ...
    'final_pitch_deg','final_yaw_deg','max_attitude_deg','pitch_ripple_deg', ...
    'rate_energy','control_energy_total','control_energy_roll', ...
    'control_energy_pitch','control_energy_yaw','compensation_energy', ...
    'disturbance_increment_iae','ifa_saturation_fraction', ...
    'baseline_command_saturation_fraction','compensation_saturation_fraction', ...
    'outer_command_saturation_fraction','solver_success','failure_reason', ...
    'runtime_seconds'};
end
