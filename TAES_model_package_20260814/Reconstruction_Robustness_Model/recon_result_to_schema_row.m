function row=recon_result_to_schema_row(job,sample,result,nominal)
% Convert one successful trajectory to the required run-level schema.

if istable(job),job=table2struct(job);end
if istable(sample),sample=table2struct(sample);end
m=compute_recon_robustness_metrics(result,nominal);
gain=local_gain(job.controller,job.k);
delta=repmat(job.delta,1,3);
actual=result.noise_meta.actual_rms;
row=table(string(job.stage),string(job.scenario_id),string(job.controller), ...
    string(job.mechanism_case),string(result.external_condition), ...
    sample.sample_id,gain(1),gain(2),gain(3),delta(1),delta(2),delta(3), ...
    job.delay_ms,job.noise_rms_fraction,result.noise_meta.seed, ...
    actual(1),actual(2),actual(3),job.filter_cutoff_hz, ...
    m.rmse_roll_deg,m.rmse_pitch_deg,m.rmse_yaw_deg,m.rmse_norm_deg, ...
    m.final_roll_deg,m.final_pitch_deg,m.final_yaw_deg,m.max_attitude_deg, ...
    m.pitch_ripple_deg,m.rate_energy,m.control_energy_total, ...
    m.control_energy_roll,m.control_energy_pitch,m.control_energy_yaw, ...
    m.compensation_energy,m.disturbance_increment_iae, ...
    m.ifa_saturation_fraction,m.baseline_command_saturation_fraction, ...
    m.compensation_saturation_fraction,m.outer_command_saturation_fraction, ...
    true,"",result.runtime_seconds,'VariableNames',recon_run_schema_names());
end

function gain=local_gain(controller,k)
switch char(controller)
    case 'C0_baseline_PD',gain=[0 0 0];
    case {'C1_selective','C3_selective_LPF'},gain=[k 0 k];
    case 'C2_all_axis',gain=[k k k];
end
end
